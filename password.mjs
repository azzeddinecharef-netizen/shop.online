import { randomBytes, scryptSync } from 'node:crypto';
import { createInterface } from 'node:readline/promises';
const rl=createInterface({input:process.stdin,output:process.stdout});
console.log('Run privately on your own computer. Input is visible in this terminal; never send the password in chat.');
const password=await rl.question('New admin password (at least 14 characters): ');
rl.close();
if(password.length<14) throw new Error('Use at least 14 characters.');
const salt=randomBytes(24).toString('hex');
console.log(`ADMIN_PASSWORD_HASH=${salt}:${scryptSync(password,salt,64).toString('hex')}`);
console.log(`SESSION_SECRET=${randomBytes(48).toString('hex')}`);
